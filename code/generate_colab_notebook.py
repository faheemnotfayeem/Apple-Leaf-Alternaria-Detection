            "    w_healthy = n_total / (2.0 * n_healthy)\n",
            "    w_alternaria = n_total / (2.0 * n_alternaria)\n",
            "    class_weights = torch.tensor([w_healthy, w_alternaria], dtype=torch.float32, device=device)\n",
